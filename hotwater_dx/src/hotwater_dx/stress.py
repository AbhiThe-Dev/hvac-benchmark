"""Model-mismatch stress test of the engine.

The engine's likelihoods are fitted on a *matched* simulated world. We then test it on cases generated by worlds that differ from the one it was fitted on
(shifted parameter ranges, milder or maximal faults, hidden asymptomatic crossover, noisier instruments, technician skips and misreads), and along a continuous
mismatch dial lambda in [0, 1]. The question is how fast accuracy falls and, above all, how often the engine is confidently wrong. Simulation only: this measures
robustness to *some* kinds of model error, not accuracy in buildings.
"""
from __future__ import annotations

import csv
import json
from dataclasses import dataclass
from pathlib import Path

import numpy as np

from . import causes as C
from . import checks as K
from . import measurement as M
from .engine import ENGINE_CONFIG, Likelihoods, PAIRS, CaseResult, fit, parts, run_case
from .matrix import World, build_world
from .provenance import DISCLAIMER
from .sampling import substream

N_FIT = 200            # plants in the world the likelihoods are fitted on
N_TEST = 100           # plants per test world
CASES_SINGLE = 510     # 30 per cause
CASES_PAIR = 99        # 9 per seeded pair
SEED_FIT = 20261101
SEED_TEST = 20261201

# parameter ranges of the shifted world (low, high): a plausible different building stock, not tuned to anything
SHIFT = {"ua_mult": (1.5, 2.3), "len_scale": (1.0, 2.0), "duty": (0.15, 0.5), "peak_frac": (0.75, 0.95), "heater_cap": (200_000, 450_000),
         "balance_err": (0.3, 0.5), "tmv_tol": (3.0, 7.0), "t_amb": (55.0, 80.0)}
NOMINAL = {"ua_mult": (1.0, 1.9), "len_scale": (0.7, 1.5), "duty": (0.25, 1.0), "peak_frac": (0.5, 0.85), "heater_cap": (250_000, 700_000),
           "balance_err": (0.1, 0.3), "tmv_tol": (1.0, 5.0), "t_amb": (60.0, 75.0)}


@dataclass(frozen=True)
class Spec:
    name: str
    shift: float = 0.0        # 0 = matched ranges, 1 = shifted ranges
    sev_mult: float = 1.0     # <1 milder faults
    sev_floor: float = 0.0    # 1.0 = every fault at maximum severity
    latent_p: float = 0.0     # share of plants with a hidden asymptomatic crossover
    noise: float = 1.0        # instrument error multiplier
    p_skip: float = 0.0       # chance a check cannot be done
    p_garbage: float = 0.0    # chance a reading is wrong (mis-performed check)

    def overrides(self):
        if self.shift == 0.0:
            return None
        return {k: ((1 - self.shift) * NOMINAL[k][0] + self.shift * SHIFT[k][0], (1 - self.shift) * NOMINAL[k][1] + self.shift * SHIFT[k][1]) for k in SHIFT}


def composite(lam: float) -> Spec:
    return Spec(f"composite_{lam:.2f}", shift=lam, sev_mult=1.0 - 0.5 * lam, latent_p=0.5 * lam, noise=1.0 + lam, p_skip=0.10 * lam, p_garbage=0.10 * lam)


WORLDS = (
    Spec("matched"),
    Spec("param_shift", shift=1.0),
    Spec("mild_faults", sev_mult=0.5),
    Spec("max_faults", sev_floor=1.0),
    Spec("latent_and_noise", latent_p=0.5, noise=2.0),
    Spec("technician_error", p_skip=0.10, p_garbage=0.10),
    composite(1.0),
)
CURVE = tuple(composite(x) for x in (0.0, 0.25, 0.5, 0.75))   # lambda = 1 is the "composite_1.00" world above

FIXED_ORDER = ("Q1", "Q2", "Q3", "K16", "K05", "K10", "K08", "K01", "K03", "K07", "K06", "K09", "K11", "K15", "K14", "K02", "K13", "K12", "K17", "K18", "K19")   # ANALYST: a plausible flowchart order

CONFIGS = {
    "A_plain": dict(),
    "B_robust": dict(var_inflate=ENGINE_CONFIG["VARIANT_B"]["var_inflate"], prior_other=ENGINE_CONFIG["VARIANT_B"]["PRIOR_OTHER"], tau=ENGINE_CONFIG["VARIANT_B"]["TAU"]),
    "S_singles_only": dict(prior_pair=0.0),
    "fixed_order": dict(selection="fixed", fixed_order=FIXED_ORDER),
    "random_order": dict(selection="random"),
    "all_checks": dict(tau=1.1, min_rate=0.0, max_checks=len(K.CHECKS)),
}


def _latent(p: float):
    def f(P, rng):
        if rng.random() < p:
            for j in rng.choice(P.n, size=int(rng.integers(1, 3)), replace=False):
                P.g_x[int(j)] = float(rng.uniform(0.02, 0.04))
    return f if p > 0 else None


def build_test_world(spec: Spec, seed: int) -> World:
    return build_world(n_theta=N_TEST, seed=seed, overrides=spec.overrides(), latent=_latent(spec.latent_p), sev_mult=spec.sev_mult, sev_floor=spec.sev_floor)


def make_cases(w: World, seed: int) -> list:
    """(truth tuple, Ctx, thermal) cases: symptomatic single-fault plants and pair-fault plants."""
    rng = np.random.default_rng(seed)
    cases = []
    singles = [cid for cid in w.cause_plants if int(w.cause_gated[cid].sum()) >= 10]
    per = max(CASES_SINGLE // max(len(singles), 1), 1)
    for cid in singles:
        idx = np.where(w.cause_gated[cid])[0]
        for j in rng.choice(idx, size=min(per, len(idx)), replace=False):
            cases.append(((cid,), w.cause_ctx[cid][int(j)], bool(w.plants[int(j)].thermal)))
    from .solve import has_complaint
    per_pair = max(CASES_PAIR // len(PAIRS), 1)
    for pi, h in enumerate(PAIRS):
        a, b = (C.BY_ID[x] for x in parts(h))
        got, tries = 0, 0
        while got < per_pair and tries < 40:
            j = int(rng.integers(len(w.plants)))
            tries += 1
            P = w.plants[j]
            da, db = a.draw(substream(w.seed, 9, pi, j, tries), P), b.draw(substream(w.seed, 9, pi, j, tries + 100), P)
            Q = b.apply(a.apply(P, da), db)
            if has_complaint(Q):
                cases.append((tuple(parts(h)), K.Ctx(Q), bool(P.thermal)))
                got += 1
    return cases


def evaluate(lk: Likelihoods, cases: list, spec: Spec, config: dict, seed: int) -> list[CaseResult]:
    out = []
    M.NOISE["scale"] = spec.noise
    try:
        for i, (truth, ctx, thermal) in enumerate(cases):
            rng = np.random.default_rng(np.random.SeedSequence([seed, i]))
            out.append(run_case(lk, ctx, truth, rng, thermal, p_skip=spec.p_skip, p_garbage=spec.p_garbage, **config))
    finally:
        M.NOISE["scale"] = 1.0
    return out


def ece(results: list[CaseResult], bins: int = 10) -> float:
    s = [r for r in results if len(r.truth) == 1]
    if not s:
        return float("nan")
    p = np.array([r.top_p for r in s])
    y = np.array([r.correct for r in s], float)
    tot = 0.0
    for b in range(bins):
        m = (p > b / bins) & (p <= (b + 1) / bins)
        if m.any():
            tot += m.mean() * abs(p[m].mean() - y[m].mean())
    return float(tot)


def metrics(results: list[CaseResult]) -> dict:
    s = [r for r in results if len(r.truth) == 1]
    pr = [r for r in results if len(r.truth) == 2]
    conf = [r for r in results if r.reason == "confident"]
    return dict(
        n_single=len(s), n_pair=len(pr),
        top1=float(np.mean([r.correct for r in s])) if s else float("nan"),
        top3_marginal=float(np.mean([r.truth[0] in sorted(r.marginal, key=r.marginal.get, reverse=True)[:3] for r in s])) if s else float("nan"),
        pair_hit=float(np.mean([r.hit for r in pr])) if pr else float("nan"),
        pair_exact=float(np.mean([r.correct for r in pr])) if pr else float("nan"),
        wrong_conf=float(np.mean([r.wrong_conf for r in results])),
        confident=float(len(conf) / len(results)),
        abstain=float(np.mean([r.reason != "confident" for r in results])),
        checks=float(np.mean([r.n_checks for r in results])),
        minutes=float(np.mean([r.minutes for r in results])),
        ece=ece(results),
        acc_when_confident=float(np.mean([r.hit for r in conf])) if conf else float("nan"),
    )


def run_all(out: Path, n_fit: int = N_FIT, configs: dict | None = None, worlds=WORLDS, curve=CURVE) -> dict:
    configs = configs or CONFIGS
    out.mkdir(parents=True, exist_ok=True)
    fit_world = build_world(n_theta=n_fit, seed=SEED_FIT)
    lk = fit(fit_world)
    rows, per_world = [], {}
    plan = [(sp, "world") for sp in worlds] + [(sp, "curve") for sp in curve]
    for wi, (spec, kind) in enumerate(plan):
        w = build_test_world(spec, SEED_TEST + wi)
        cases = make_cases(w, SEED_TEST + 1000 + wi)
        names = list(configs) if kind == "world" else ["A_plain", "B_robust"]
        for cname in names:
            res = evaluate(lk, cases, spec, configs[cname], SEED_TEST + 2000 + wi)
            m = metrics(res)
            m.update(world=spec.name, config=cname, kind=kind)
            rows.append(m)
        per_world[spec.name] = len(cases)
    with open(out / "engine_stress.csv", "w", newline="") as f:
        wr = csv.writer(f)
        wr.writerow(["# " + DISCLAIMER])
        cols = ["kind", "world", "config", "n_single", "n_pair", "top1", "top3_marginal", "pair_hit", "pair_exact", "wrong_conf", "confident", "abstain", "acc_when_confident", "checks", "minutes", "ece"]
        wr.writerow(cols)
        for m in rows:
            wr.writerow([m[c] if not isinstance(m[c], float) else f"{m[c]:.3f}" for c in cols])
    (out / "engine_stress.json").write_text(json.dumps(dict(disclaimer=DISCLAIMER, rows=rows, config_hash=__import__("hotwater_dx.engine", fromlist=["config_hash"]).config_hash()), indent=1, default=float) + "\n")
    write_report(out, rows)
    return dict(rows=rows, n_cases=per_world)


def frozen_hash() -> str:
    """sha256 over everything that defines the engine and the stress test (recorded in PREREGISTRATION.md before the run)."""
    import hashlib

    from .engine import ENGINE_CONFIG, _strkeys
    blob = dict(engine=_strkeys(ENGINE_CONFIG), N_FIT=N_FIT, N_TEST=N_TEST, CASES_SINGLE=CASES_SINGLE, CASES_PAIR=CASES_PAIR, SEED_FIT=SEED_FIT, SEED_TEST=SEED_TEST, SHIFT=SHIFT, NOMINAL=NOMINAL,
                worlds=[vars(x) if hasattr(x, "__dict__") else str(x) for x in WORLDS], curve=[str(x) for x in CURVE], fixed_order=FIXED_ORDER, configs={k: {a: str(b) for a, b in v.items()} for k, v in CONFIGS.items()})
    return hashlib.sha256(json.dumps(blob, sort_keys=True, default=str).encode()).hexdigest()


# ------------------------------------------------------------------------------------------------ scorecard and report (rules frozen in PREREGISTRATION.md Addendum 3)
def _get(rows, world, config, kind=None):
    for r in rows:
        if r["world"] == world and r["config"] == config and (kind is None or r["kind"] == kind):
            return r
    return None


def scorecard(rows: list[dict]) -> list[tuple[str, bool, str]]:
    m = _get(rows, "matched", "A_plain")
    out = []
    out.append(("E1", m["top1"] >= 0.70 and m["wrong_conf"] <= 0.05, f"matched A: top-1 {m['top1']:.2f} (>= 0.70), wrong-and-confident {m['wrong_conf']:.3f} (<= 0.05)"))
    out.append(("E2", m["checks"] <= 8 and m["minutes"] <= 60, f"matched A: {m['checks']:.1f} checks (<= 8), {m['minutes']:.0f} min (<= 60)"))
    f = _get(rows, "matched", "fixed_order")
    out.append(("E3", m["minutes"] <= f["minutes"] and m["top1"] >= f["top1"] - 0.02,
                f"matched: engine {m['minutes']:.0f} min / top-1 {m['top1']:.2f} vs fixed order {f['minutes']:.0f} min / {f['top1']:.2f}"))
    c1 = _get(rows, "composite_1.00", "A_plain", "world")
    c1b = _get(rows, "composite_1.00", "B_robust", "world")
    mb = _get(rows, "matched", "B_robust")
    out.append(("E4", c1["wrong_conf"] > 0.10 and c1b["wrong_conf"] <= 0.7 * c1["wrong_conf"] and mb["top1"] >= m["top1"] - 0.05,
                f"composite lambda=1: A wrong-and-confident {c1['wrong_conf']:.3f} (> 0.10), B {c1b['wrong_conf']:.3f} (<= 0.7 x A); matched top-1 B {mb['top1']:.2f} vs A {m['top1']:.2f} (within 0.05)"))
    ms = _get(rows, "matched", "S_singles_only")
    out.append(("E5", m["pair_hit"] >= 0.70 and m["pair_hit"] >= ms["pair_hit"] + 0.05, f"matched pair cases: A hit {m['pair_hit']:.2f} (>= 0.70) vs singles-only {ms['pair_hit']:.2f} (A >= S + 0.05)"))
    curve = [r for r in rows if r["config"] == "A_plain" and r["world"].startswith("composite_") and r["world"] != "composite_1.00" or (r["world"] == "composite_1.00" and r["kind"] == "world" and r["config"] == "A_plain")]
    curve = sorted(curve, key=lambda r: float(r["world"].split("_")[1]))
    t = [r["top1"] for r in curve]
    mono = all(b <= a + 0.03 for a, b in zip(t, t[1:]))
    out.append(("E6", mono and (t[0] - t[-1]) <= 0.25, "top-1 along lambda " + ", ".join(f"{x:.2f}" for x in t) + f" (non-increasing within 0.03; total drop {t[0] - t[-1]:.2f} <= 0.25)"))
    # recommended variant (decision rule)
    worlds = sorted({r["world"] for r in rows if r["kind"] == "world"})
    b_better = all(_get(rows, w, "B_robust", "world")["wrong_conf"] <= _get(rows, w, "A_plain", "world")["wrong_conf"] + 1e-9 for w in worlds)
    rec = "B_robust" if b_better and mb["top1"] >= m["top1"] - 0.05 else "A_plain"
    out.append(("RECOMMENDED", rec == "B_robust", f"decision rule gives {rec} (B wrong-and-confident <= A in every world: {b_better}; matched top-1 within 0.05: {mb['top1'] >= m['top1'] - 0.05})"))
    return out


def write_report(out: Path, rows: list[dict]) -> None:
    sc = scorecard(rows)
    L = ["# Engine stress test (simulation only)", "", f"**{DISCLAIMER}**", "",
         "The engine's likelihoods are fitted on a matched simulated world; cases come from worlds that differ from it. This measures robustness to *some kinds* of model error, not accuracy in buildings.", "",
         "## Scorecard (rules and predictions frozen before the run)", "", "| | holds | evidence |", "|---|---|---|"]
    for k, ok, ev in sc:
        L.append(f"| {k} | {'yes' if ok else 'NO'} | {ev} |")
    L += ["", "## Worlds x configurations", "", "top1 = exact single-fault diagnosis; pair_hit = names at least one true component of a two-fault case; wrong_conf = stopped 'confident' with no true component; "
          "abstain = stopped without reaching the confidence bar.", "",
          "| world | config | top1 | pair_hit | wrong_conf | confident | abstain | acc when confident | checks | minutes | ECE |", "|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        if r["kind"] != "world":
            continue
        L.append(f"| {r['world']} | {r['config']} | {r['top1']:.2f} | {r['pair_hit']:.2f} | {r['wrong_conf']:.3f} | {r['confident']:.2f} | {r['abstain']:.2f} | {r['acc_when_confident']:.2f} | {r['checks']:.1f} | {r['minutes']:.0f} | {r['ece']:.3f} |")
    L += ["", "## Mismatch dial (composite world, lambda 0 -> 1)", "", "| lambda | config | top1 | wrong_conf | confident | checks | minutes |", "|---|---|---|---|---|---|---|"]
    for r in sorted((r for r in rows if r["world"].startswith("composite_") and r["config"] in ("A_plain", "B_robust")), key=lambda r: (float(r["world"].split("_")[1]), r["config"])):
        L.append(f"| {r['world'].split('_')[1]} | {r['config']} | {r['top1']:.2f} | {r['wrong_conf']:.3f} | {r['confident']:.2f} | {r['checks']:.1f} | {r['minutes']:.0f} |")
    (out / "ENGINE_STRESS_REPORT.md").write_text("\n".join(L) + "\n")
