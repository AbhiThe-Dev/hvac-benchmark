"""Does deliberate setpoint perturbation identify the serving box where passive data cannot? (PREREGISTRATION_DR.md Addendum 13)
Reads the campaigns generated by scripts/45; scores zone-to-box identification per campaign length and noise level; compares with the passive
`vav_zone` channels on the undithered baseline run of the same building/season. Nothing is fitted. Never touches SEALED data or T1-T6 suites.
  .venv/bin/python doc_mismatch/scripts/46_perturbation_eval.py
"""
import pickle
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from docmismatch.data import load_base  # noqa: E402
from docmismatch.dr import diagnosability as D  # noqa: E402
from docmismatch.dr import perturbation as P  # noqa: E402
from docmismatch.evidence import make_context, pair_errors  # noqa: E402

CAMP = ROOT.parent / "results" / "docmismatch" / "perturbation" / "campaigns"
OUT = ROOT.parent / "results" / "docmismatch" / "perturbation"
BUILDINGS = ["sys07_vav_reheat", "vav_2ahu_2loops", "vav_3ahu_2loops", "dev_E", "dev_F", "dev_G", "dev_H"]
SEASONS = ["july", "january"]
SEEDS = (1, 2, 3)
LENGTHS = [24, 48, 96, 168, 288]
NOISES = ["none", "legacy", "harsh"]
PRE = 48
N_DRAWS = 20


def truth_and_ids(b):
    zones, vavs = sorted(b.ids("Zone")), sorted(b.ids("VAV"))
    own = {m: o for o, m in b.slot_edges["vav_zone"]}
    return zones, vavs, np.array([vavs.index(own[z]) for z in zones])


def active(season, tid):
    """{noise: {L: mean rank-1 over code seeds}}"""
    per_seed = []
    for s in SEEDS:
        b = load_base(tid, CAMP / season / f"seed{s}")
        zones, vavs, truth = truth_and_ids(b)
        U, Y = P.campaign_arrays(b.ev, zones, vavs, PRE)
        per_seed.append({nz: P.sweep(U, Y, truth, LENGTHS, nz, N_DRAWS, 1000 * s) for nz in NOISES})
    return {nz: {L: float(np.mean([r[nz][L] for r in per_seed])) for L in LENGTHS} for nz in NOISES}, len(vavs)


def passive(season, tid):
    """{channel-set: {L: rank-1}} from the existing passive channels on the undithered baseline of the same campaign window."""
    b = load_base(tid, CAMP / season / "baseline")
    owners, members, truth, cands = D.slot_layout(b, "vav_zone")
    n_days = (len(next(iter(b.ev.values()))) - PRE) // 24
    E = np.full((n_days, 3, len(owners), len(members)), np.nan)
    for d in range(n_days):
        sl = slice(PRE + d * 24, PRE + (d + 1) * 24)
        c = make_context(b, b.ev, sl)
        for a, o in enumerate(owners):
            for k, m in enumerate(members):
                E[d, :, a, k] = pair_errors(b, b.ev, "vav_zone", o, m, sl, c, mask_uninformative=False)
    out = {}
    for name in ("all3", "ch1"):
        out[name] = {L: D.rank1_accuracy(E[: L // 24], truth, cands, np.zeros(L // 24, dtype=int), D.CHANNEL_SETS[name], pooled=True)["acc"] for L in LENGTHS}
    return out


def fmt(x):
    return f"{x['est']:.2f} [{x['lo']:.2f}, {x['hi']:.2f}]"


def main():
    f = OUT / "perturbation_eval.pkl"
    if f.exists():
        res = pickle.loads(f.read_bytes())
        print("loaded from cache")
    else:
        res = {}
        for season in SEASONS:
            for tid in BUILDINGS:
                a, n_vav = active(season, tid)
                res[(season, tid)] = dict(active=a, passive=passive(season, tid), n_vav=n_vav)
                print(f"  {season:8s} {tid:18s} n_vav={n_vav} legacy@96h={a['legacy'][96]:.2f} passive(all3)@96h={res[(season, tid)]['passive']['all3'][96]:.2f}", flush=True)
        f.write_bytes(pickle.dumps(res))

    md = ["# Does deliberate setpoint perturbation identify the serving box where passive data cannot? (Addendum 13)", "",
          "7 train-role topologies (each counts equally), code seeds 1-3, 20 noise draws each; rank-1 = fraction of zones whose most-responsive box is the true serving box; "
          "chance = 1/n_vav (about 0.10). `legacy` noise = the project's original telemetry noise; `harsh` = flow x N(1,0.10), temperature + N(0,1.0). "
          "Passive = the existing `vav_zone` channels on the UNDITHERED run of the same building and window. Building-cluster bootstrap 95% CI (500). Simulation only.", ""]
    verdict = {}
    for season in SEASONS:
        md += [f"## {season}", "", "| campaign length | " + " | ".join(f"active, {nz} noise" for nz in NOISES) + " | passive all3 | passive ch1 |", "|---|" + "---|" * (len(NOISES) + 2)]
        for L in LENGTHS:
            row = [fmt(D.boot_mean([res[(season, t)]["active"][nz][L] for t in BUILDINGS])) for nz in NOISES]
            row += [fmt(D.boot_mean([res[(season, t)]["passive"][k][L] for t in BUILDINGS])) for k in ("all3", "ch1")]
            md.append(f"| {L} h | " + " | ".join(row) + " |")
        md += ["", f"Per building, active `legacy` noise: " + ", ".join(f"{t} " + "/".join(f"{res[(season, t)]['active']['legacy'][L]:.2f}" for L in (24, 96, 288)) for t in BUILDINGS) + "  (L = 24/96/288 h)", ""]
        leg96 = D.boot_mean([res[(season, t)]["active"]["legacy"][96] for t in BUILDINGS])["est"]
        pas96 = D.boot_mean([res[(season, t)]["passive"]["all3"][96] for t in BUILDINGS])["est"]
        first = next((L for L in LENGTHS if D.boot_mean([res[(season, t)]["active"]["legacy"][L] for t in BUILDINGS])["est"] >= 0.90), None)
        verdict[season] = dict(leg96=leg96, pas96=pas96, first=first)
    md += ["## Frozen reading rules (Addendum 13)", ""]
    for season, v in verdict.items():
        md.append(f"- {season}: legacy-noise rank-1 at 96 h = {v['leg96']:.3f} (needs >= 0.90); passive all3 at 96 h = {v['pas96']:.3f} (needs <= 0.30); shortest L reaching 0.90 = {v['first']}")
    ok96 = all(v["leg96"] >= 0.90 and v["pas96"] <= 0.30 for v in verdict.values())
    any288 = any(v["first"] is not None for v in verdict.values())
    if ok96:
        md.append("\n**VERDICT: perturbation BREAKS THE PASSIVE LIMIT** (both seasons, L = 96 h).")
    elif all(v["first"] is not None for v in verdict.values()):
        md.append("\n**VERDICT: WORKS BUT NEEDS THE LONG CAMPAIGN** (0.90 reached in both seasons, but not both at 96 h).")
    elif any288:
        md.append("\n**VERDICT: SEASON-LIMITED** (0.90 reached in only one season).")
    else:
        md.append("\n**VERDICT: does NOT solve the problem** (0.90 not reached in either season by 288 h).")
    (OUT / "perturbation_eval_report.md").write_text("\n".join(md))
    print("\n".join(md))


main()
